#!/usr/bin/env bash
#
# ingest-fp.sh — 取り込み元マーカーの **フィンガープリント `fp`** を算出する（読み取り専用）。
#
# 使い方（コピー&ペーストで再現できる 1 コマンド）:
#
#   gh issue view <番号> --repo <owner>/<repo> --json body -q .body \
#     | "${CLAUDE_PLUGIN_ROOT}/scripts/ingest-fp.sh"
#   #=> 12 桁の小文字 16 進（例: 4a5a0c9f20fd）
#
#   標準入力に **取得したての外部 Issue 本文**（他は何も足さない）を渡し、12 桁を得る。
#
#   `--from-ledger-quote` を付けると、正規化の**前に**ブロック引用マーカー（各行の行頭の
#   `>` と、その直後の空白 1 つまで）を 1 段だけ剥がす。**旧 fp からの移行周に、台帳の説明欄の
#   原文引用が外部本文と実質同一かを照合する**ためだけのモード:
#
#     sed -n '<説明欄のブロック引用の範囲>p' challenge-ledger.md \
#       | "${CLAUDE_PLUGIN_ROOT}/scripts/ingest-fp.sh" --from-ledger-quote
#
#   出た 12 桁が外部本文の 12 桁と一致すれば「移行可」、しなければ「比較不能」。
#   **この照合を目視・LLM の推定で行わない**——それは本スクリプトが断ったはずの穴を
#   移行で作り直すことにあたる（移行の窓は一度きりで、取りこぼしは二度と回収できない）。
#
# なぜスクリプトなのか（本ファイルの存在理由）:
#   以前の `fp` は「台帳に書いた人間記入欄（説明・完了条件・緊急度）を散文の規約に従って
#   正規化・連結してハッシュする」ものだった。規約は散文であり実装が無かったため、**毎周
#   読み手が手で再実装**していた。結果、同じ誤り（引用行にもインデント・リストマーカー除去を
#   適用する）が 4 回再発し、うち 1 回は誤った `fp` を台帳へ書き込むところまで進んだ
#   （2026-08-21 / 08-26 / 08-27 / 08-29）。入力を外部本文へ移すと台帳の文字列を経由しなく
#   なるため解釈余地は大きく減るが、**正規化が散文のままでは消えない**。算式を 1 箇所の実装に
#   固定して初めて再発が構造的に断たれる（Issue #130）。
#
# 正規化（この 4 つだけ。ここに書いていない変換は一切行わない）:
#   1. CR（U+000D）をすべて削除する（CRLF → LF。孤立 CR も削除）
#   2. 各行の**行末**の空白（スペース・タブ）を削除する
#   3. 文字列**全体**の前後の空白（改行を含む）を削除する
#   4. それ以外は変更しない。本文中の空行・インデント・引用マーカー（`>`）・リストマーカー・
#      大文字小文字はすべて**意味のある差**として値に反映する
#
#   `--from-ledger-quote` はこの 1〜4 の**前に** 0 番目の規則を 1 つだけ足す:
#   0. 各行の行頭の `>` と、その直後の空白 1 つまでを削除する（1 段だけ。`> > x` は `> x` に
#      なる＝外部本文側の引用が復元される）。引用でない行は変更しない（黙って捨てない）
#
#   1〜3 は「人間には見えないのに値が動く」差だけを落とすためにある。GitHub の Web エディタ・
#   `gh` の往復・シェルの `$(...)`（末尾改行を落とす）はいずれもこの種の差を勝手に作るため、
#   落としておかないと**中身が変わっていない周に「更新あり」と誤判定**する。逆に 4 は
#   「見えている差は必ず値に出る」＝更新検知そのものであり、緩めてはならない。
#
#   ※ 3 のおかげで、パイプ（`gh ... | ingest-fp.sh`）でもコマンド置換
#     （`printf '%s' "$body" | ingest-fp.sh`）でも同じ値になる。
#
# ハッシュ:
#   正規化後の**バイト列**（UTF-8 のまま。文字単位の正規化・Unicode 正規化は行わない）の
#   `sha256` の先頭 12 桁（小文字 16 進）。12 桁は人間が読まない HTML コメントに収める長さで、
#   台帳規模（〜数百エントリ）では衝突を実務上無視できる。
#
# 依存: bash / perl / shasum（`shasum` は perl パッケージ同梱。`templates/container/Dockerfile`
#       が perl を明示導入しているのはこの算式のため）。ネットワークに触れない。
#
# 終了コード:
#   0  算出して stdout へ出力した
#   2  未知の引数が渡された（入力は stdin 専用。受け付けるフラグは --from-ledger-quote だけ）
#
# 規定の正本: skills/ingest-challenges/SKILL.md §4「フィンガープリント `fp`」。
# テスト: scripts/tests/ingest-fp.test.sh（ゴールデン値つき）。

set -euo pipefail

FROM_LEDGER_QUOTE=0
if [ "$#" -eq 1 ] && [ "$1" = "--from-ledger-quote" ]; then
  FROM_LEDGER_QUOTE=1
elif [ "$#" -gt 0 ]; then
  cat >&2 <<'USAGE'
ingest-fp.sh: 入力は標準入力です。受け付けるフラグは --from-ledger-quote だけです。

  gh issue view <番号> --repo <owner>/<repo> --json body -q .body | ingest-fp.sh
  sed -n '<引用の範囲>p' challenge-ledger.md | ingest-fp.sh --from-ledger-quote
USAGE
  exit 2
fi

# 正規化 → sha256 の先頭 12 桁。シェル変数を経由しない（NUL バイト・末尾改行の欠落を避ける）。
# LC_ALL=C: perl をバイト意味論に固定し、`\s` の解釈がロケールで揺れないようにする。
LC_ALL=C FP_FROM_LEDGER_QUOTE="$FROM_LEDGER_QUOTE" perl -0777 -pe '
  s/\r//g;                                  # 1. CR をすべて削除
  s/^>[ ]?//mg if $ENV{FP_FROM_LEDGER_QUOTE}; # 0. （台帳引用のみ）引用マーカーを 1 段剥がす
  s/[ \t]+$//mg;                            # 2. 各行の行末空白を削除
  s/\A\s+//;                                # 3a. 全体の先頭の空白を削除
  s/\s+\z//;                                # 3b. 全体の末尾の空白を削除
' | shasum -a 256 | cut -c1-12
